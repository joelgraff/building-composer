#!/usr/bin/env node
/**
 * Refreshes Composer's bundled copy of the Dixon game's material manifest
 * (js/game-materials-data.js) from the game's checkout:
 *
 *   node scripts/sync-game-materials.mjs [path/to/materials_manifest.json]
 *
 * The default path is ../dixon_dem/game/data/materials_manifest.json. The
 * bundled copy is what Composer uses when it isn't served by the game's
 * composer_server.py (which serves the live one at /game-materials).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.argv[2] ?? resolve(root, '../dixon_dem/game/data/materials_manifest.json'));
const manifest = JSON.parse(readFileSync(source, 'utf8'));
if (manifest.format !== 'dixon-materials' || !Array.isArray(manifest.materials)) {
  throw new Error(`${source} is not a Dixon materials manifest`);
}
const out = resolve(root, 'js/game-materials-data.js');
writeFileSync(out, `/**
 * The Dixon game's material manifest, as bundled with Composer (see
 * js/game-materials.js). Generated by scripts/sync-game-materials.mjs from
 * dixon_dem/game/data/materials_manifest.json; don't edit by hand.
 */
export default ${JSON.stringify(manifest, null, 2)};
`);
console.log(`wrote ${out} (${manifest.materials.length} materials, hash ${manifest.hash})`);
